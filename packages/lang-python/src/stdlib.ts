/** Standard-library modules with declarations. */
export const PYTHON_LIBRARIES: ReadonlyArray<string> = Object.keys(STUBS);

/** The stub of a standard-library module, if known. */
export function pythonLibrary(
  module: string
): { text: string; fileName: string } | undefined {
  const text = STUBS[module];
  return text === undefined
    ? undefined
    : {
        text: text.trimStart(),
        fileName: `stdlib/${module.replaceAll('.', '/')}.py`,
      };
}
